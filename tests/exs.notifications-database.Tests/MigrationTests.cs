	/// <summary>
	/// Applies this repo's migrations to a real PostgreSQL instance and checks the schema they produce.
	///
	/// This is the only coverage the migrations have. Every other suite builds its schema from the model
	/// via EnsureCreated and never executes a migration, so a migration can be wrong in ways that still
	/// compile and still pass all of them - that is not hypothetical, an earlier hand-edit dropped two
	/// columns from fcm_sent (where NotificationQueueProcessor needs them) instead of fcm_queue and
	/// nothing went red. InitialFcmTransport is hand-edited by design, so it needs executing somewhere.
	///
	/// The context comes from NotificationDatabaseContextFactory rather than being built here, so the
	/// real design-time configuration - replaced SQL generator and model differ, and the
	/// __EFMigrationsHistory_Notifications history table - is what gets exercised.
	/// </summary>
	public sealed class MigrationTests : IAsyncLifetime
	{
		private readonly PostgreSqlContainer mPostgres = new PostgreSqlBuilder()
			.WithImage("postgres:16-alpine")
			.Build();

		private string? mPreviousConnectionStringVariable;

		/// <summary>
		/// The slice of the api-server's schema this repo's migrations depend on. InitialFcmTransport
		/// adds a column to notification and points a foreign key at it, but does not create it - that
		/// table belongs to server-side-base-api-server's migrations
		/// (main-database/Migrations/20260831152713_InitialCreate), and this repo only ever reads it.
		/// Standing it up by hand is what reproduces the real topology: a database where the api-server
		/// has already migrated and this repo's migrations run on top.
		/// </summary>
